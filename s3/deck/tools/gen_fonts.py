"""Anti-aliased bitmap fonts for the round UI: ASCII 32..126, 4 bits of coverage a pixel.

Writes main/ui/fonts.cpp + fonts.h. Fonts are DejaVu (Bitstream Vera licence: embedding is
fine). Sizes are pixels per em; the UI picks the nearest one for the screen it's on.

    python3 tools/gen_fonts.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "main", "ui")
DJ = "/usr/share/fonts/truetype/dejavu/"
FACES = {
    "Sans": (DJ + "DejaVuSansCondensed.ttf", [10, 12, 14, 16, 18, 20, 24]),
    "Bold": (DJ + "DejaVuSansCondensed-Bold.ttf", [10, 12, 14, 16, 18, 20, 24, 28, 32, 40, 48]),
}

def glyphs(path, size):
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    out = []
    for code in range(32, 127):
        ch = chr(code)
        adv = round(f.getlength(ch))
        l, t, r, b = f.getbbox(ch)            # relative to the top of the ascent box
        w, h = max(0, r - l), max(0, b - t)
        rows = []
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255)
            px = im.load()
            for y in range(h):
                row = [(px[x, y] + 8) // 17 for x in range(w)]   # 0..15
                if len(row) % 2: row.append(0)
                rows += [row[i] << 4 | row[i + 1] for i in range(0, len(row), 2)]
        out.append(dict(w=w, h=h, dx=l, dy=t - asc, adv=adv, bits=rows))
    cap = -min(g["dy"] for g, c in zip(out, range(32, 127)) if chr(c) == "H")
    return out, asc, desc, cap

def main():
    h = ["// Generated by tools/gen_fonts.py: don't edit.", "#pragma once", '#include "rgfx.h"', "namespace fonts {"]
    c = ["// Generated by tools/gen_fonts.py from DejaVu Sans Condensed (Bitstream Vera licence).",
         '#include "fonts.h"', "namespace fonts {"]
    table = []
    for face, (path, sizes) in FACES.items():
        for size in sizes:
            name = f"k{face}{size}"
            gs, asc, desc, cap = glyphs(path, size)
            bits, off, gl = [], 0, []
            for g in gs:
                gl.append(f"{{{off},{g['w']},{g['h']},{g['dx']},{g['dy']},{g['adv']}}}")
                bits += g["bits"]; off += len(g["bits"])
            c.append(f"static const uint8_t {name}_bits[] = {{{','.join(map(str, bits))}}};")
            c.append(f"static const rgfx::Glyph {name}_g[] = {{{','.join(gl)}}};")
            c.append(f"const rgfx::Font {name} = {{ {name}_bits, {name}_g, {size}, {cap}, {desc}, {asc + desc} }};")
            h.append(f"extern const rgfx::Font {name};")
            table.append((face, size, name))
    for face in FACES:
        names = [n for f, s, n in table if f == face]
        h.append(f"// all {face} sizes, smallest first")
        h.append(f"extern const rgfx::Font* const k{face}All[{len(names)}];")
        c.append(f"const rgfx::Font* const k{face}All[{len(names)}] = {{{', '.join('&' + n for n in names)}}};")
    h.append("} // namespace fonts")
    c.append("} // namespace fonts")
    open(os.path.join(OUT, "fonts.h"), "w").write("\n".join(h) + "\n")
    open(os.path.join(OUT, "fonts.cpp"), "w").write("\n".join(c) + "\n")
    print("fonts:", ", ".join(n for _, _, n in table))

main()
