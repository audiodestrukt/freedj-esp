#!/usr/bin/env python3
"""Bakes the screen's fonts into a C header for the display processor: DejaVu
Sans at two sizes (labels and titles; the big bold readouts), printable
ASCII, one 8-bit coverage value per pixel in fixed-height cells, each glyph
as wide as its advance.

  python3 tools/font.py <out.h>
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONTS = "/usr/share/fonts/truetype/dejavu/"
FACES = [("font_small", "DejaVuSans.ttf", 13), ("font_label", "DejaVuSans-Bold.ttf", 11), ("font_big", "DejaVuSans-Bold.ttf", 30)]


def bake(name, path, size):
    f = ImageFont.truetype(FONTS + path, size)
    ascent, descent = f.getmetrics()
    h = ascent + descent
    widths, offsets, data = [], [], bytearray()
    for c in range(32, 127):
        w = max(1, round(f.getlength(chr(c))))
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((0, 0), chr(c), font=f, fill=255)
        widths.append(w)
        offsets.append(len(data))
        data += img.tobytes()
    out = [f"static const uint8_t {name}_data[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        out.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const uint8_t {name}_w[95] = {{ {', '.join(map(str, widths))} }};")
    out.append(f"static const uint32_t {name}_off[95] = {{ {', '.join(map(str, offsets))} }};")
    out.append(f"static const font {name} = {{ {h}, {name}_w, {name}_off, {name}_data }};")
    return "\n".join(out)


if __name__ == "__main__":
    body = ["/* Generated by tools/font.py from DejaVu (Bitstream Vera licence). Do not edit. */",
            "#pragma once", "#include <stdint.h>",
            "typedef struct { uint8_t h; const uint8_t *w; const uint32_t *off; const uint8_t *data; } font;"]
    body += [bake(*f) for f in FACES]
    open(sys.argv[1], "w").write("\n".join(body) + "\n")
