"""gen_geom.py: the control board's mechanical anchors, from the enclosure CAD, as
lib/geom.json in the tscircuit frame (board centre = 0,0; +x right, +y toward the back).

Everything the case fixes comes from ../cad (machine_params.py, ctrlboard.py): the outline,
the three screw holes, the switch centres, the LED circle under the ring skirts, the skirt
keep-out ring and the connector positions. Run it after any change there:
    python3 gen_geom.py
"""
import json, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "cad"))
os.environ.setdefault("FREEDJ_CONFIG", "flat")   # anchors are the same in both configs
import machine_params as M
import ctrlboard as CB

x0, y0, x1, y1 = M.CTRL_XY
cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
T = lambda x, y: [round(x - cx, 4), round(y - cy, 4)]
geom = {
    "_note": "generated by gen_geom.py from ../cad; do not edit",
    "board": {"width": x1 - x0, "height": y1 - y0, "cornerRadius": M.CTRL_CORNER_R,
              "deckOrigin": [x0, y0], "deckCentre": [cx, cy]},
    "holes": [T(x, y) for x, y in M.CTRL_HOLES],
    "holeDiameter": CB.HOLE_D,
    "bossDiameter": M.CTRL_BOSS_D,
    "buttons": {"play": T(*M.PLAY_C), "cue": T(*M.CUE_C)},
    "ledRadius": CB.LED_R,
    "ledAngles": list(CB.LED_ANGLES),
    "skirt": {"inner": M.SKIRT_D / 2 - M.SKIRT_WALL, "outer": M.SKIRT_D / 2},
    "jst": {n: {"pins": p, "at": T(x, y), "along": a} for n, p, x, y, a in CB.JST},
}
os.makedirs("lib", exist_ok=True)
json.dump(geom, open("lib/geom.json", "w"), indent=2)
print("wrote lib/geom.json:", geom["board"]["width"], "x", geom["board"]["height"], "mm")
